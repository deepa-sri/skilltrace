export const DICTS = { en, mr, hi };
export const LANGS = [
  { code: "en", label: "English" },
  { code: "mr", label: "मराठी" },
  { code: "hi", label: "हिंदी" },
];

const I18nContext = createContext({ lang: "en", t: (k) => en[k] || k, setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState("en");
  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("skilltrace.lang");
      if (saved && DICTS[saved]) setLangState(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l) => {
    setLangState(l);
    try {
      window.localStorage.setItem("skilltrace.lang", l);
    } catch {}
  }, []);
  const t = useCallback((k) => DICTS[lang]?.[k] || en[k] || k, [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
